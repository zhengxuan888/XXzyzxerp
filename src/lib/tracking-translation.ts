export function translateTrackingDescription(value: string | null | undefined) {
  const text = value?.trim();
  if (!text) return null;
  if (/\p{Script=Han}/u.test(text)) return text;
  return translationRules.find(([pattern]) => pattern.test(text))?.[1] ?? null;
}
